/* Maps semantic core events (enum FlEvent) to sounds and vibration.
   Sound ids refer to the WAV set generated by make_sounds.py (see audio.h).
   Provisional: replace the files, not the mapping, to change the sounds. */
(function (root, factory) {
  if (typeof module === "object" && module.exports) module.exports = factory();
  else root.CockpitEvents = factory();
})(typeof self !== "undefined" ? self : this, function () {
  "use strict";
  var EV = { FIRE: 1, ROCK_BREAK: 2, HIT: 3, WARNING: 4, MANUAL_REQUIRED: 5, AUTOPILOT_ON: 6,
             AUTOPILOT_REFUSED: 7, LOW_FUEL: 8, HULL_CRITICAL: 9, ARRIVED: 10, DESTROYED: 11, STRANDED: 12 };
  var SOUND = {}; SOUND[EV.FIRE] = 10; SOUND[EV.ROCK_BREAK] = 6; SOUND[EV.HIT] = 13; SOUND[EV.WARNING] = 8;
  SOUND[EV.MANUAL_REQUIRED] = 15; SOUND[EV.AUTOPILOT_ON] = 4; SOUND[EV.AUTOPILOT_REFUSED] = 3;
  SOUND[EV.LOW_FUEL] = 12; SOUND[EV.HULL_CRITICAL] = 9; SOUND[EV.ARRIVED] = 1;
  SOUND[EV.DESTROYED] = 5; SOUND[EV.STRANDED] = 2;
  var VIBRATE = {}; VIBRATE[EV.HIT] = [80, 40, 80]; VIBRATE[EV.WARNING] = [200];
  VIBRATE[EV.MANUAL_REQUIRED] = [120, 60, 120]; VIBRATE[EV.DESTROYED] = [400];
  function soundFor(ev) { return Object.prototype.hasOwnProperty.call(SOUND, ev) ? SOUND[ev] : 0; }
  function vibrationFor(ev) { return Object.prototype.hasOwnProperty.call(VIBRATE, ev) ? VIBRATE[ev] : null; }
  return { EV: EV, soundFor: soundFor, vibrationFor: vibrationFor };
});
